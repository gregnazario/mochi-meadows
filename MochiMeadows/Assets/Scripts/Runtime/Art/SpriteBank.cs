        // Rebuild the player sprites with a new outfit (called at boot and on makeover).
        public static void RebuildPlayerSprites(Color dress, Color hair)
        {
            DressColor = dress;
            HairColor = hair;
            var pal = new Dictionary<char, Color>
            {
                ['h'] = hair, ['H'] = Color.Lerp(hair, Color.black, 0.22f),
                ['c'] = Palette.Skin, ['k'] = Palette.EyePlum,
                ['w'] = Palette.White, ['b'] = Palette.Blush,
                ['p'] = dress, ['P'] = Color.Lerp(dress, Color.black, 0.18f),
                ['s'] = Palette.Cream, ['d'] = Color.Lerp(dress, Color.black, 0.28f),
            };
            PlayerDown0 = S("PlayerDown0", true, PlayerPal, ArtDown0);
            PlayerDown1 = S("PlayerDown1", true, PlayerPal, ArtDown1);
            PlayerUp0 = S("PlayerUp0", true, PlayerPal, ArtUp0);
            PlayerUp1 = S("PlayerUp1", true, PlayerPal, ArtUp1);
            PlayerSide0 = S("PlayerSide0", true, PlayerPal, ArtSide0);
            PlayerSide1 = S("PlayerSide1", true, PlayerPal, ArtSide1);
        }

