        {
            return S(name, false, pal, rows);
        }

        static readonly Color OutlineColor = new Color(0.36f, 0.27f, 0.33f, 0.88f);


        static Sprite S(string name, bool outline, Dictionary<char, Color> pal, params string[] rows)
        {
            var ps = PixelSprite.From(name, rows, pal);
            if (outline) ps = ps.Outlined(OutlineColor);
            return SpriteFactory.ToSprite(ps);
        }
